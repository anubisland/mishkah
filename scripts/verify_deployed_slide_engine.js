const extractFn = (name) => {
  const start = html.indexOf(`function ${name}(`);
  let depth = 0;
  let bodyStart = html.indexOf('{', start);
  let i = bodyStart;
  for (; i < html.length; i++) {
    if (html[i] === '{') depth++;
    else if (html[i] === '}') {
      depth--;
      if (depth === 0) break;
    }
  }
  return html.substring(start, i + 1);
};

